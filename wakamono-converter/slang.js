(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.Slang = factory();
})(typeof self !== "undefined" ? self : this, function () {
  // 各エントリは3候補。元の言葉（複数表記可）→ 若者言葉
  const RAW = [
    [["ありがとうございます", "ありがとう"], ["あざます", "サンクス", "あざまる水産"]],
    [["こんにちは"], ["ちーっす", "やっほー", "おつかれ〜"]],
    [["おはようございます", "おはよう"], ["おは〜", "おはよ！", "おっは〜"]],
    [["さようなら", "さよなら"], ["ばいばーい", "じゃーね", "またね〜ノシ"]],
    [["本当に", "本当", "ほんとうに"], ["マジで", "ガチで", "リアルに"]],
    [["とても", "すごく", "非常に", "かなり"], ["めっちゃ", "ちょー", "バチバチに"]],
    [["すごい", "凄い"], ["エグい", "ヤバい", "えぐち"]],
    [["最高", "さいこう"], ["神", "優勝", "最強"]],
    [["最悪"], ["詰んだ", "ムリすぎ", "終わってる"]],
    [["かわいい", "可愛い"], ["きゃわ", "きゃわたん", "尊い"]],
    [["かっこいい", "格好いい", "カッコいい"], ["イケてる", "シュッとしてる", "えぐいカッコよさ"]],
    [["面白い", "おもしろい"], ["ウケる", "草", "ツボ"]],
    [["美味しい", "おいしい"], ["うまっ", "神うま", "うますぎ"]],
    [["楽しい"], ["アガる", "エモい", "テンション爆上がり"]],
    [["嬉しい", "うれしい"], ["アガる", "ブチ上がる", "ハピすぎ"]],
    [["悲しい", "かなしい"], ["しんどい", "メンタルやられた", "えもい"]],
    [["疲れた", "つかれた"], ["しんどい", "溶けた", "HP0"]],
    [["恥ずかしい"], ["はずい", "はずかちい", "顔から火が出る"]],
    [["気持ち悪い"], ["キモい", "キショい", "生理的にムリ"]],
    [["面倒くさい", "面倒", "めんどくさい"], ["めんどい", "だるい", "ダルすぎ"]],
    [["微妙"], ["ビミョー", "ちょい違う", "うーん"]],
    [["驚いた", "びっくりした"], ["ビビった", "は？ってなった", "心臓止まった"]],
    [["大好き", "好き"], ["推せる", "沼", "ガチ恋"]],
    [["嫌い"], ["ムリ", "地雷", "受け付けない"]],
    [["友達", "友だち"], ["ダチ", "マブダチ", "なかま"]],
    [["彼氏"], ["カレピ", "カレシ氏", "ピ"]],
    [["彼女"], ["カノピ", "カノジョ氏", "ピ"]],
    [["頑張る", "がんばる"], ["ガチる", "気合い入れる", "アゲてく"]],
    [["寝る"], ["寝落ちする", "ベッドに溶ける", "おやすみモード"]],
    [["そうですね", "その通り"], ["それな", "わかりみ", "ほんとそれ"]],
    [["わかる", "分かる"], ["わかりみ", "それな", "ワカる〜"]],
    [["ですね"], ["っすね", "だね〜", "だわ〜"]],
    [["です"], ["っす", "だよ", "だわ"]],
  ];

  const DICT = new Map();
  for (const [keys, variants] of RAW) for (const k of keys) DICT.set(k, variants);
  const KEYS = Array.from(DICT.keys()).sort((a, b) => b.length - a.length);

  // 辞書にない言葉用のテンプレ（正確な変換ではなく、遊びの装飾）
  const FALLBACK = [
    (w) => `${w}、マジ神すぎん？`,
    (w) => `${w}ってガチでエモい`,
    (w) => `${w}は優勝です、ほんとそれ`,
  ];

  /** variantIndex(0〜2) の候補で text を変換する */
  function convert(text, variantIndex) {
    const v = ((variantIndex % 3) + 3) % 3;
    const parts = [];
    let hits = 0;
    let buf = "";
    let i = 0;
    while (i < text.length) {
      const key = KEYS.find((k) => text.startsWith(k, i));
      if (key) {
        if (buf) parts.push({ t: buf, hit: false });
        buf = "";
        parts.push({ t: DICT.get(key)[v], hit: true });
        hits++;
        i += key.length;
      } else {
        buf += text[i++];
      }
    }
    if (buf) parts.push({ t: buf, hit: false });
    if (hits === 0 && text.trim()) {
      return { parts: [{ t: FALLBACK[v](text.trim()), hit: true }], hits: 0, fallback: true };
    }
    return { parts, hits, fallback: false };
  }

  const toText = (r) => r.parts.map((p) => p.t).join("");

  return { convert, toText, DICT, KEYS };
});
